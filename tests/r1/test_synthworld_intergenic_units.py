CODE11_BY_AA = {
    "F": "TTT TTC", "L": "TTA TTG CTT CTC CTA CTG", "I": "ATT ATC ATA", "M": "ATG", "V": "GTT GTC GTA GTG",
    "S": "TCT TCC TCA TCG AGT AGC", "P": "CCT CCC CCA CCG", "T": "ACT ACC ACA ACG", "A": "GCT GCC GCA GCG",
    "Y": "TAT TAC", "*": "TAA TAG TGA", "H": "CAT CAC", "Q": "CAA CAG", "N": "AAT AAC", "K": "AAA AAG",
    "D": "GAT GAC", "E": "GAA GAG", "C": "TGT TGC", "W": "TGG", "R": "CGT CGC CGA CGG AGA AGG",
    "G": "GGT GGC GGA GGG",
}
CODE11 = {c: aa for aa, cs in CODE11_BY_AA.items() for c in cs.split()}
STARTS = {"ATG", "GTG", "TTG"}
STOPS = {"TAA", "TAG", "TGA"}
PAIRS_OK = {("A", "T"), ("T", "A"), ("G", "C"), ("C", "G"), ("G", "T"), ("T", "G")}


def rc(s: str) -> str:
    return "".join({"A": "T", "C": "G", "G": "C", "T": "A"}[c] for c in reversed(s))


def protein(cds: str) -> str:
    aa = [CODE11[cds[i:i + 3]] for i in range(0, len(cds), 3)]
    return "M" + "".join(aa[1:])


def _cfg() -> dict:
    return copy.deepcopy(backbone.load_preset("micro")["intergenic"])


def _junction_cfg() -> dict:
    J = _cfg()["junctions"]
    J["loose"]["max"] = 200
    J["divergent"]["max"] = 400
    J["convergent"]["max"] = 240
    return J


LAY = intergenic.Layout(u_len=200, d_len=120, sp1=17, utr_a=10, utr_b=10, sp2=7, term_start=5, stem=8, loop=4,
                        t_tract=7)


def _random_cds(rng, n_codons: int, start="ATG", stop="TAA", second=None) -> str:
    sense = [c for c, a in CODE11.items() if a != "*"]
    body = [sense[int(i)] for i in rng.integers(len(sense), size=n_codons)]
    if second is not None:
        body[0] = second
    return start + "".join(body) + stop


def _gene(rng, label, strand, *, family=1, unit="", z=(0.0, 0.0, 0.0), cds=None, m=0, lay=LAY):
    u = "".join(rng.choice(list("ACGT"), size=lay.u_len))
    d = "".join(rng.choice(list("ACGT"), size=lay.d_len))
    cas = intergenic.CopyCassette(label, "n1", u, d, z, lay, m)
    return intergenic.GeneIn(label, family, strand, unit, cds or _random_cds(rng, 40), cas)



def test_the_normal_quantile_is_the_standard_one():
    nd = statistics.NormalDist()
    for u in (0.01, 0.3, 0.5, 0.9):
        assert intergenic.phi_inv(u) == nd.inv_cdf(u)
        assert abs(intergenic.phi(intergenic.phi_inv(u)) - u) < 1e-12

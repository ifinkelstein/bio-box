def test_motif_evolution_changes_pairs_only_into_canonical_pairs():
    model = rna.synthetic_models(backbone.load_preset("micro")["rna_motifs"],
                                 _cfg()["cassettes"]["pair_weights"], 11)[0]
    e = rna.synthetic_emit(model, 1, np.random.default_rng(3))[0]
    pairs = np.array(e.pairs)
    paired = np.zeros(len(e.seq), bool)
    paired[pairs.ravel()] = True
    unp = np.nonzero(~paired)[0]
    comp = np.cumsum([0.3, 0.2, 0.2, 0.3])
    pair_cum = np.cumsum([0.15, 0.15, 0.3, 0.3, 0.05, 0.05])
    rng = np.random.default_rng(9)
    counts = np.zeros(4)
    changed_pairs = 0
    for _ in range(300):
        m = rna.to_codes(e.seq)
        rna.evolve_motif(m, pairs, unp, 2.0, comp, pair_cum, rng)
        s = rna.to_str(m)
        assert all((s[i], s[j]) in PAIRS_OK for i, j in e.pairs)
        changed_pairs += sum(s[i] != e.seq[i] or s[j] != e.seq[j] for i, j in e.pairs)
        counts += np.bincount(m[unp], minlength=4)
    # unpaired bases after 2 expected events are near the composition (1 - e^-2 of them redrawn)
    f = counts / counts.sum()
    assert np.allclose(f, [0.3, 0.2, 0.2, 0.3], atol=0.06), f
    assert changed_pairs > 0


# --- overlaps (§2.4 "overlaps -1 (TAATG) and -4 (ATGA) realized by templates") ----------------------------

@pytest.mark.parametrize("stop", sorted(STOPS))
@pytest.mark.parametrize("start", sorted(STARTS))
@pytest.mark.parametrize("last", ["AAA", "AAC", "AAG", "AAT"])
@pytest.mark.parametrize("second", ["ACG", "GCG"])
def test_overlap_edits_are_protein_neutral_templates(stop, start, last, second):
    rng = np.random.default_rng(0)
    up = _random_cds(rng, 30, "ATG", stop)
    up = up[:-6] + last + stop
    down = _random_cds(rng, 30, start, "TAA", second=second)
    for o in (1, 4):
        ed = intergenic.overlap_edits(up, down, o)
        # when an edit is possible, by the rules written out here
        if o == 1:
            possible = True
        else:
            possible = last[2] != "C" and second[0] == "A"
        assert (ed is not None) == possible, (o, stop, start, last, second)
        if ed is None:
            continue
        assert ed["stop"] in STOPS and ed["start"] in STARTS
        new_up = up[:-3] + ed["stop"]
        new_down = ed["start"] + down[3:]
        assert new_up[-o:] == new_down[:o]
        assert protein(new_up) == protein(up) and protein(new_down) == protein(down)
        if o == 4:
            assert new_up[-4:] == last[2] + "TGA" and new_down[:4] == last[2] + "TGA"
        else:
            assert new_up[-3:] + new_down[1:3] in ("TAATG", "TGATG", "TAGTG")



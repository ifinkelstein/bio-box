def test_junction_types_follow_strands_and_the_rules():
    rng = np.random.default_rng(2)
    J = _junction_cfg()
    a, b = _gene(rng, "n1_g1", 1, family=3), _gene(rng, "n1_g2", 1, family=4)
    assert intergenic.junction(a, b, J, 1).kind in ("codir_tight", "codir_loose")
    ga, gb = _gene(rng, "n1_g1", 1, unit="mod00/7"), _gene(rng, "n1_g2", 1, unit="mod00/7")
    assert intergenic.junction(ga, gb, J, 1).rule == "group"
    assert intergenic.junction(ga, gb, J, 1).kind == "codir_tight"
    dv = intergenic.junction(_gene(rng, "n1_g1", -1), _gene(rng, "n1_g2", 1), J, 1)
    cv = intergenic.junction(_gene(rng, "n1_g1", 1), _gene(rng, "n1_g2", -1), J, 1)
    assert dv.kind == "divergent" and cv.kind == "convergent"
    # the same ordered pair of families gets the same class whatever the copies; the class depends on the order
    kinds = {intergenic.junction(_gene(rng, "x_g1", 1, family=9), _gene(rng, "x_g2", 1, family=12), J, 4).kind
             for _ in range(5)}
    assert len(kinds) == 1
    kinds_minus = {intergenic.junction(_gene(rng, "x_g1", -1, family=12), _gene(rng, "x_g2", -1, family=9), J, 4).kind
                   for _ in range(5)}
    assert kinds_minus == kinds          # 9 then 12 in transcription order on either strand


